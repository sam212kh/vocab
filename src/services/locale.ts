function readLocale(): AppLocale {
    if (typeof localStorage === 'undefined') return 'en'

    try {
        return localStorage.getItem(STORAGE_KEY) === 'fa' ? 'fa' : 'en'
    } catch {
        return 'en'
    }
}

function applyDocumentLocale(value: AppLocale): void {
    if (typeof document === 'undefined') return

    document.documentElement.lang = value === 'fa' ? 'fa' : 'en'
    document.documentElement.dir = value === 'fa' ? 'rtl' : 'ltr'
}

export function setLocale(value: AppLocale): void {
    locale.value = value
    applyDocumentLocale(value)
    refreshLocaleDom()

    try { localStorage.setItem(STORAGE_KEY, value) } catch { /* storage may be disabled */ }
}

export function useLocale(): {
    locale: Ref<AppLocale>
    isPersian: ComputedRef<boolean>
    t: (key: string, params?: Record<string, string>) => string
    setLocale: (value: AppLocale) => void
} {
    const isPersian = computed(() => locale.value === 'fa')
    const t = (key: string, params: Record<string, string> = {}) => {
        const fallback = messages.en[key] ?? key
        const message = messages[locale.value][key] ?? fallback

        return Object.entries(params).reduce(
            (result, [name, value]) => result.replaceAll(`{${name}}`, value),
            message,
        )
    }

    return { locale, isPersian, t, setLocale }
}

export function translateText(text: string, value: AppLocale = locale.value): string {
    const key = Object.keys(messages.en).find(candidate => messages.en[candidate] === text)
    if (key) return messages[value][key] ?? text

    if (value === 'fa' && staticTranslations[text]) return staticTranslations[text]
    if (value === 'fa' && legacyExactTranslations.has(text)) return legacyExactTranslations.get(text)!
    if (value === 'fa') {
        const dueWords = text.match(/^(\d+) words? due for spaced-repetition review, mixed with a few new words\.$/)
        if (dueWords) return `${dueWords[1]} واژه برای مرور فاصله‌دار آماده است و چند واژه جدید هم دارد.`

        const dueGrammar = text.match(/^(\d+) grammar topics? due for spaced review \((.*)\)\.$/)
        if (dueGrammar) return `${dueGrammar[1]} موضوع گرامر برای مرور فاصله‌دار آماده است (${dueGrammar[2]}).`

        const hardWords = text.match(/^(\d+) words? marked hard are waiting, and there's time left in today's budget\.$/)
        if (hardWords) return `${hardWords[1]} واژه دشوار در انتظار مرور است و هنوز از زمان امروز باقی مانده است.`

        const hardWordsAudioCoverage = text.match(/^(\d+) of (\d+) have audio and examples available to repeat here — the rest were saved from content that isn't in the vocabulary library \(e\.g\. a reading or listening passage\), so there's nothing to play for them on this screen\. They're still saved — see$/)
        if (hardWordsAudioCoverage) return `${hardWordsAudioCoverage[1]} واژه از ${hardWordsAudioCoverage[2]} واژه دشوار در این صفحه صدا و مثال دارند — باقی از محتوایی ذخیره شده‌اند که بخشی از کتابخانه واژگان نیست (مثلاً یک متن خواندنی یا شنیداری)، بنابراین چیزی برای پخش در این صفحه ندارند. آن‌ها همچنان ذخیره شده‌اند — مشاهده کنید`

        const hardWordsNonePlayable = text.match(/^(\d+) hard words? saved — none have audio here$/)
        if (hardWordsNonePlayable) return `${hardWordsNonePlayable[1]} واژه دشوار ذخیره شده — هیچ‌کدام در اینجا صدا ندارند`

        const reviewDueWords = text.match(/^Review (\d+) due words?$/)
        if (reviewDueWords) return `مرور ${reviewDueWords[1]} واژه سررسیده`

        const continueExpression = text.match(/^Continue · expression (\d+) of (\d+)$/)
        if (continueExpression) return `ادامه · عبارت ${continueExpression[1]} از ${continueExpression[2]}`

        const expressionProgress = text.match(/^Expression (\d+) of (\d+)$/)
        if (expressionProgress) return `عبارت ${expressionProgress[1]} از ${expressionProgress[2]}`

        const stepProgress = text.match(/^Step (\d+) \/ (\d+)$/)
        if (stepProgress) return `گام ${stepProgress[1]} از ${stepProgress[2]}`

        const wordProgress = text.match(/^Word (\d+) of (\d+)$/)
        if (wordProgress) return `واژه ${wordProgress[1]} از ${wordProgress[2]}`

        const moreExamples = text.match(/^(\d+) more example(s?)$/)
        if (moreExamples) return `${moreExamples[1]} مثال دیگر`

        const messageCount = text.match(/^(\d+) messages?$/)
        if (messageCount) return `${messageCount[1]} پیام`

        const wordsWritten = text.match(/^(\d+) words?$/)
        if (wordsWritten) return `${wordsWritten[1]} واژه`

        const minutes = text.match(/^about (\d+) min$/)
        if (minutes) return `حدود ${minutes[1]} دقیقه`

        // Deliberately do not translate fragments inside arbitrary text. The
        // legacy DOM bridge sees lesson titles, vocabulary and user content;
        // substring replacement corrupts those values. Dynamic UI copy must
        // use an explicit `t('...')` key at its presentation boundary.
        return text
    }
    return text
}

/** Exposes the key inventory to deterministic localization tests and tooling. */
export function translationKeys(prefix = ''): string[] {
    return Object.keys(messages.en).filter(key => key.startsWith(prefix))
}

type LocaleDomBridge = { stop: () => void; refresh: () => void }
let activeBridge: LocaleDomBridge | null = null

/** Translate known UI copy rendered by existing views without touching lesson content. */
export function installLocaleDomBridge(root: HTMLElement): LocaleDomBridge {
    const originalText = new WeakMap<Text, string>()
    const originalAttributes = new WeakMap<Element, Map<string, string>>()
    let applying = false

    const translateNode = (node: Node): void => {
        if (node.nodeType === Node.TEXT_NODE) {
            const text = node as Text
            const parent = text.parentElement
            if (!parent || ['SCRIPT', 'STYLE', 'TEXTAREA'].includes(parent.tagName) || parent.isContentEditable) return

            const source = originalText.get(text) ?? text.data
            originalText.set(text, source)
            const trimmed = source.trim()
            if (!trimmed) return
            const translated = translateText(trimmed)
            if (translated !== trimmed) {
                const start = source.indexOf(trimmed)
                const next = `${source.slice(0, start)}${translated}${source.slice(start + trimmed.length)}`
                if (text.data !== next) text.data = next
            } else if (locale.value === 'en' && text.data !== source) {
                text.data = source
            }
            return
        }

        if (node.nodeType !== Node.ELEMENT_NODE) return
        const element = node as Element
        if (['SCRIPT', 'STYLE', 'TEXTAREA'].includes(element.tagName) || element.hasAttribute('data-locale-ignore')) return

        for (const attribute of ['placeholder', 'aria-label', 'title']) {
            if (!element.hasAttribute(attribute)) continue
            const values = originalAttributes.get(element) ?? new Map<string, string>()
            const source = values.get(attribute) ?? element.getAttribute(attribute) ?? ''
            values.set(attribute, source)
            originalAttributes.set(element, values)
            const next = locale.value === 'fa' ? translateText(source) : source
            if (element.getAttribute(attribute) !== next) element.setAttribute(attribute, next)
        }

        for (const child of Array.from(element.childNodes)) translateNode(child)
    }

    const refresh = () => {
        if (applying) return
        applying = true
        translateNode(root)
        applying = false
    }

    const observer = new MutationObserver(() => refresh())
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'aria-label', 'title'] })
    activeBridge = { stop: () => observer.disconnect(), refresh }
    refresh()
    return activeBridge
}

export function refreshLocaleDom(): void {
    activeBridge?.refresh()
}

