// Usage: node scripts/content-gap-report.mjs [--out docs/CONTENT_GAPS.md]
// Reproducible content coverage report, generated only from the files under public/data.
import { writeFileSync } from 'node:fs'

import { BANDS } from '../src/services/contentGap.ts'
import { coverageReport } from '../src/services/contentCoverage.ts'
import { summarizeIssues, validateContent } from '../src/services/contentValidation.ts'
import { loadRepoContent } from './content-load.mjs'

const content = loadRepoContent()
const report = coverageReport(content)
const issues = validateContent(content)
const summary = summarizeIssues(issues)

const pct = value => `${Math.round(value * 100)}%`
const row = cells => `| ${cells.join(' | ')} |`
const table = (head, rows) => [row(head), row(head.map(() => '---')), ...rows.map(row)]
const band5 = BANDS.slice(0, 5)
const inv = report.inventory

const areaLabel = { grammar: 'Grammar', listening: 'Listening', reading: 'Reading', 'real-life': 'Real-Life' }

const lines = [
    '# Content coverage report',
    '',
    'Generated by `npm run report:content` (`node scripts/content-gap-report.mjs --out docs/CONTENT_GAPS.md`) from the files under `public/data`. Every figure is counted from the content. CEFR bands are **author-assigned tags**, not an external rating; ranges such as A2-B1 count in each band they span. Vocabulary courses carry course labels, not CEFR tags, so they are not in the CEFR tables. No AI is used to produce or judge anything here.',
    '',
    '## 1. Inventory',
    '',
    ...table(['Content', 'Count'], [
        ['Vocabulary courses / words', `${inv.vocabularyCourses} / ${inv.vocabularyWords.toLocaleString('en-US')}`],
        ['Real-Life scenarios / taught expressions', `${inv.realLifeScenarios} / ${inv.realLifeExpressions}`],
        ['Grammar topics / examples', `${inv.grammarTopics} / ${inv.grammarExamples}`],
        ['Listening activities / spoken lines', `${inv.listeningActivities} / ${inv.listeningLines}`],
        ['Reading passages / paragraphs', `${inv.readingPassages} / ${inv.readingParagraphs}`],
        ['Speaking topics / steps', `${inv.speakingTopics} / ${inv.speakingSteps}`],
        ['Writing prompts', inv.writingPrompts],
        ['Conversation scenarios', inv.conversationScenarios],
        ['Exercises (Grammar, Listening, Reading, Real-Life)', inv.exercises],
        ['Learning objectives', inv.objectives],
        ['Transfer patterns / situations', `${inv.transferPatterns} / ${inv.transferSituations}`],
    ]),
    '',
    'Exercise types: ' + Object.entries(report.exerciseTypes).sort((a, b) => b[1] - a[1]).map(([type, count]) => `${type} ${count}`).join(', ') + '.',
    '',
    '## 2. Automated validation',
    '',
    `\`npm run validate:content\`: **${summary.errors} error(s), ${summary.warnings} warning(s).** Errors fail the check; warnings are quality gaps.`,
    '',
    ...(summary.byCode.length ? table(['Severity', 'Count', 'Rule'], summary.byCode.map(item => [item.severity, item.count, item.code])) : ['No issues.']),
    '',
    '## 3. Topics by CEFR band',
    '',
    ...table(['Area', 'Topics', ...band5], report.areas.map(area => [areaLabel[area.area], area.topics, ...band5.map(band => area.byBand[band])])),
    '',
    '## 4. Exercises by CEFR band (authored tags only)',
    '',
    ...table(['Area', 'Items', ...BANDS, 'Untagged', 'Holes'], report.cefr.map(item => [item.area, item.total, ...BANDS.map(band => item.perBand[band]), item.untagged, item.holes.join(', ') || '–'])),
    '',
    '## 5. Recognition, recall and production',
    '',
    '"Recognition" = choose an option, match or arrange given words. "Word recall" = type a word or phrase from a cue (fill in the blank, a short dictation). "Sentence" = type a whole sentence (translation, short answer, correction, writing response, or a dictation of four or more words, which is transcription, not production). "Open production" below counts speaking, writing and role-play tasks.',
    '',
    ...table(['Area', 'Exercises', 'Recognition', 'Word recall', 'Sentence', 'Typed share'], report.areas.map(area => [areaLabel[area.area], area.exercises, area.recognition, area.recall, area.sentence, area.exercises ? pct((area.recall + area.sentence) / area.exercises) : '–'])),
    '',
    `Open production tasks: ${inv.speakingSteps ? report.listeningSpeaking.reduce((sum, item) => sum + item.speakingOpenSteps, 0) : 0} open speaking prompts, ${inv.writingPrompts} writing prompts, ${report.listeningSpeaking.reduce((sum, item) => sum + item.roleplays, 0)} Real-Life role-plays, ${inv.conversationScenarios} conversation scenarios and ${inv.transferSituations} transfer situations.`,
    '',
    '## 6. Listening and speaking by band',
    '',
    ...table(['Band', 'Listening activities', 'Listening exercises', 'Dictation', 'Speaking topics', 'Repeat steps', 'Open steps', 'Real-Life speaking tasks', 'Role-plays', 'Conversation', 'Writing prompts'], report.listeningSpeaking.map(item => [item.band, item.listeningActivities, item.listeningExercises, item.dictation, item.speakingTopics, item.speakingRepeatSteps, item.speakingOpenSteps, item.realLifeSpeakingTasks, item.roleplays, item.conversationScenarios, item.writingPrompts])),
    '',
    'Speaking support is transcript comparison against the model sentence, never phoneme-level pronunciation scoring. Open speaking answers are recorded, not scored.',
    '',
    '## 7. Topics: activity coverage and objectives',
    '',
    ...table(['Topic', 'Level', 'Exercises', 'Recognition', 'Word recall', 'Sentence', 'Listening', 'Speaking', 'Objectives (assessed / total)', 'Flags'], report.topics.map(topic => [
        topic.id, topic.cefr, topic.exercises, topic.recognition, topic.recall, topic.sentence, topic.listening, topic.speaking || topic.roleplay ? 'yes' : 'no',
        `${topic.objectives.filter(objective => objective.exercises > 0).length} / ${topic.objectives.length}`, topic.issues.join(', ') || '–',
    ])),
    '',
    '## 8. Objective coverage',
    '',
    ...table(['Topic', 'Objective', 'Exercises', 'Recognition', 'Word recall', 'Sentence'], report.topics.flatMap(topic => topic.objectives.filter(objective => objective.exercises === 0 || objective.recall + objective.sentence === 0).map(objective => [topic.id, objective.id, objective.exercises, objective.recognition, objective.recall, objective.sentence]))),
    '',
    'Only objectives that are unassessed or assessed by recognition alone are listed. If the table is empty every objective has a typed exercise.',
    '',
    '## 9. Transfer pattern coverage',
    '',
    'A pattern can only be used when the learner has recalled a taught expression that matches it ("anchors"). Anchors count Real-Life expressions.',
    '',
    ...table(['Pattern', 'Level', 'Taught anchors', 'Situations', 'Difficulty levels', 'Explained', 'Situations with feedback', 'Avg. reference answers'], report.patterns.map(pattern => [pattern.pattern, pattern.cefr, pattern.anchors, pattern.contexts, pattern.levels.join(', '), pattern.hasExplanation ? 'yes' : 'no', `${pattern.contextsWithFeedback} / ${pattern.contexts}`, pattern.averageReferences])),
    '',
    '## 10. Vocabulary examples and contexts',
    '',
    ...table(['Course', 'Words', 'Examples/word', 'Boilerplate examples', 'Boilerplate context sentences', 'Distinct mini-contexts', 'Usage notes', 'Mistake notes'], report.repetition.map(item => [item.label, item.words, item.examplesPerWord, pct(item.repeatedExampleShare), pct(item.repeatedContextShare), item.distinctMiniContexts, item.withUsageNote, item.withMistakeNote])),
    '',
    '## 11. Prioritized gaps',
    '',
    '`priority = impact × 3 + reach` (impact always outranks reach). Impact 3 removes a rung of the evidence ladder, 2 weakens evidence quality, 1 is coverage polish. Reach 3 / 2 / 1 is the affected share of its area: at least 60% / 25% / below 25%.',
    '',
    ...(report.findings.length ? table(['#', 'Priority', 'Gap', 'Evidence', 'Affected', 'Why it matters', 'Suggested action'], report.findings.map((item, index) => [index + 1, `${item.priority} (impact ${item.impact}, reach ${item.reach})`, item.title, item.evidence, `${item.affected} of ${item.of}`, item.impactWhy, item.action])) : ['No gaps found by these rules.']),
    '',
    '## Method limits',
    '',
    '- Boilerplate = a sentence that, with the headword masked, recurs for at least 5 words and 5% of the course. It detects sameness, not quality.',
    '- Anchors count only Real-Life expressions. Career and conversation content can add more but is not taught in the Daily Journey.',
    '- Nothing here judges whether the English or the Persian is good. That needs a human reviewer.',
    '',
]

const outIndex = process.argv.indexOf('--out')

if (outIndex > -1) writeFileSync(process.argv[outIndex + 1], lines.join('\n'))
else console.log(lines.join('\n'))
